/** 3 918 000 → «3 918 000 ₽». Неразрывные пробелы, чтобы число не рвалось. */
export function formatRub(value: number): string {
  return `${value.toLocaleString('ru-RU').replace(/\s/g, '\u00A0')}\u00A0₽`
}
